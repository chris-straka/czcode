import { sign as signApplication, type SignOptions } from "@electron/osx-sign";
import { expect, it, vi } from "vite-plus/test";

import sign from "./sign-macos.ts";

vi.mock("@electron/osx-sign", () => ({ sign: vi.fn() }));

it("batches codesign calls without changing existing signing options", async () => {
  const options = {
    app: "/tmp/czcode.app",
    identity: "Developer ID Application: cz Tools, Inc.",
    keychain: "/tmp/czcode.keychain",
    provisioningProfile: "/tmp/czcode.provisionprofile",
    optionsForFile: () => ({
      entitlements: "/tmp/czcode.entitlements.plist",
      hardenedRuntime: true,
    }),
  } satisfies SignOptions;

  await sign(options);

  expect(signApplication).toHaveBeenCalledExactlyOnceWith({
    ...options,
    batchCodesignCalls: true,
  });
});
